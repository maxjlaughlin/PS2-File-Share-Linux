def testparm(conf: Optional[str] = None) -> Result:
    binary = which("testparm")
    if not binary:
        return Result(127, "", "testparm not found — is Samba installed?")
    cmd = [binary, "-s"]
    if conf:
        cmd.append(conf)
    return run(cmd, timeout=30)


def apply(cfg: Config, *, dry_run: bool = False) -> ApplyOutcome:
    """Write the share config, validate it, and reload Samba.

    On any validation failure both files are restored from the backups taken
    at the start, so a bad apply can never leave the server unshareable.
    """
    if not cfg.share_path:
        return ApplyOutcome(False, "Pick a folder to share first.")
    if not os.path.isdir(cfg.share_path):
        return ApplyOutcome(False, f"{cfg.share_path} is not a directory.")

    text = render_config(cfg)
    # A preview is useful even before Samba is installed.
    if dry_run:
        return ApplyOutcome(True, "Preview only — nothing was written.", config_text=text)

    if not samba_installed():
        return ApplyOutcome(
            False,
            "Samba is not installed.",
            "Install it first — Debian/Ubuntu: apt install samba · Fedora/RHEL: dnf install samba · Arch: pacman -S samba",
        )

    if not is_root():
        return ApplyOutcome(False, "Applying the share needs root. Run the app with sudo or as a systemd service.")

    conf = smb_conf_path()
    target = include_path(conf)

    conf_backup = backup_file(conf)
    include_backup = backup_file(target)
    original_conf = ""
    if os.path.isfile(conf):
        with open(conf, "r", encoding="utf-8", errors="replace") as handle:
            original_conf = handle.read()

    def rollback() -> None:
        if conf_backup and os.path.isfile(conf_backup):
            with open(conf_backup, "r", encoding="utf-8", errors="replace") as handle:
                atomic_write(conf, handle.read())
        elif original_conf:
            atomic_write(conf, original_conf)
        elif os.path.isfile(conf):
            os.unlink(conf)
        if include_backup and os.path.isfile(include_backup):
            with open(include_backup, "r", encoding="utf-8", errors="replace") as handle:
                atomic_write(target, handle.read())
        elif os.path.isfile(target):
            os.unlink(target)

    try:
        atomic_write(target, text)
        atomic_write(conf, add_include(original_conf, target))
    except OSError as exc:
        rollback()
        return ApplyOutcome(False, "Could not write the Samba configuration.", str(exc))

    check = testparm(conf)
    # Older/newer Samba builds disagree about a handful of parameter names.
    # Rather than guess the version, drop whatever this build rejects and retry.
    unknown = unknown_parameters(check.out + "\n" + check.err)
    if unknown:
        text = strip_parameters(text, unknown)
        atomic_write(target, text)
        check = testparm(conf)

    if not check.ok:
        rollback()
        return ApplyOutcome(
            False,
            "Samba rejected the generated configuration — nothing was changed.",
            (check.err or check.out).strip(),
            config_text=text,
        )

    reloaded = reload_samba()
    status = samba_status()
    smbd_active = bool(status.get("smbd", {}).get("active"))
    if not smbd_active:
        started = control_service("start")
        if not started.ok:
            detail = (started.err or started.out).strip()
            if "booted with systemd" in detail or "Failed to connect to bus" in detail:
                detail = (
                    "systemd is not running here (a container or chroot), so the service "
                    "could not be started for you. The config is written and valid — start "
                    "Samba with whatever this system uses, e.g. `smbd -D`."
                )
            return ApplyOutcome(
                False,
                "Config written and validated, but smbd could not be started.",
                detail,
                config_text=text,
                written=True,
            )
    elif not reloaded.ok:
        return ApplyOutcome(
            False,
            "Config written, but reloading smbd failed.",
            (reloaded.err or reloaded.out).strip(),
            config_text=text,
            written=True,
        )

    note = ""
    if unknown:
        note = "This Samba build does not support: " + ", ".join(unknown) + " (commented out)."
    return ApplyOutcome(
        True, f"Share '{cfg.share_name}' is live.", note, config_text=text, written=True
    )


def unapply() -> ApplyOutcome:
    """Remove the include block and the generated file, leaving smb.conf as it was."""
    if not is_root():
        return ApplyOutcome(False, "Removing the share needs root.")
    conf = smb_conf_path()
    target = include_path(conf)
    if os.path.isfile(conf):
        backup_file(conf)
        with open(conf, "r", encoding="utf-8", errors="replace") as handle:
            atomic_write(conf, remove_include(handle.read()))
    if os.path.isfile(target):
        os.unlink(target)
    reload_samba()
    return ApplyOutcome(True, "The PS2 share was removed from Samba.")

def resolve_force_user(cfg: Config) -> str:
    """Which unix account Samba should act as when touching the share.

    Never root by default: with guest access that would hand anyone on the
    network root-owned writes inside the share.  An explicit choice is
    respected, but the UI warns about it.
    """
    if cfg.force_user:
        return cfg.force_user
    if cfg.access_mode == "user" and user_exists(cfg.username):
        return cfg.username
    if cfg.share_path:
        owner = owner_of_path(cfg.share_path)
        if owner and owner != "root":
            return owner
    return "nobody"


def render_config(cfg: Config) -> str:
    """Build the contents of ps2share.conf."""
    force_user = resolve_force_user(cfg)
    force_group = group_of_user(force_user) or "nogroup"
    guest = cfg.access_mode == "guest"
    max_proto = "NT1" if cfg.smb1_only else "SMB3"
    ports = "445 139" if cfg.enable_netbios else "445"

    lines: List[str] = [
        "# Generated by PS2 File Share. Changes here are overwritten on the next apply.",
        "# Edit the settings in the web UI instead, or stop the app and manage this file yourself.",
        "",
        "[global]",
        f"   workgroup = {cfg.workgroup}",
        '   server string = PS2 File Share',
        "",
        "   # --- Open PS2 Loader needs the SMB1 dialect (NT LM 0.12) ---",
        "   server min protocol = NT1",
        f"   server max protocol = {max_proto}",
        f"   smb ports = {ports}",
        "   client min protocol = NT1",
        "",
        "   # --- OPL authenticates with NTLMv1, which Samba disables by default ---",
        "   ntlm auth = yes",
        "   server signing = disabled",
        "   smb encrypt = off",
        "   restrict anonymous = 0",
    ]

    if cfg.lanman_auth:
        # Deprecated in Samba, so only written when someone asks for it.
        lines += ["   lanman auth = yes", "   client lanman auth = yes"]

    if guest:
        lines += [
            "",
            "   # --- open (guest) access ---",
            "   map to guest = Bad User",
            "   guest account = " + force_user,
            "   security = user",
        ]
    else:
        lines += [
            "",
            "   # --- password protected access ---",
            "   security = user",
            "   map to guest = Never",
        ]

    lines += [
        "",
        "   # --- the PS2 cannot speak the unix extensions; turning them off also",
        "   #     lets the share follow symlinks onto other disks ---",
        "   unix extensions = no",
    ]

    if cfg.tuned_performance:
        lines += [
            "",
            "   # --- throughput tuning (a PS2 tops out around 10 MB/s on 100 Mbit) ---",
            "   socket options = TCP_NODELAY IPTOS_LOWDELAY",
            "   use sendfile = yes",
            "   min receivefile size = 16384",
            "   aio read size = 16384",
            "   aio write size = 16384",
            "   deadtime = 30",
        ]

    lines += [
        "",
        "   # --- keep the logs small; the web UI tails them ---",
        "   log level = 1",
        "   max log size = 2000",
        "",
        f"[{cfg.share_name}]",
        "   comment = PS2 games for Open PS2 Loader",
        f"   path = {cfg.share_path}",
        "   browseable = yes",
        f"   read only = {'no' if cfg.writable else 'yes'}",
        f"   guest ok = {'yes' if guest else 'no'}",
    ]

    if not guest:
        lines.append(f"   valid users = {cfg.username}")

    lines += [
        f"   force user = {force_user}",
        f"   force group = {force_group}",
        "   create mask = 0664",
        "   directory mask = 0775",
        "   force create mode = 0664",
        "   force directory mode = 0775",
        "",
        "   # --- OPL does not understand oplock breaks and never locks files ---",
        "   oplocks = no",
        "   level2 oplocks = no",
        "   kernel oplocks = no",
        "   strict locking = no",
        "",
        "   # --- no DOS attribute or extended attribute round-trips per file ---",
        "   store dos attributes = no",
        "   ea support = no",
        "   map archive = no",
        "   map hidden = no",
        "   map system = no",
        "   map readonly = no",
        "",
    ]

    if cfg.wide_links:
        lines += [
            "   # --- let the share point at games living on other mounts ---",
            "   follow symlinks = yes",
            "   wide links = yes",
            "",
        ]
    else:
        lines += [
            "   # --- symlinks may not escape the shared folder ---",
            "   follow symlinks = yes",
            "   wide links = no",
            "",
        ]
    return "\n".join(lines)


UNKNOWN_PARAM_RE = re.compile(r'[Uu]nknown parameter encountered:?\s*"([^"]+)"')
IGNORING_PARAM_RE = re.compile(r'Ignoring unknown parameter\s*"([^"]+)"')


def unknown_parameters(testparm_output: str) -> List[str]:
    """Parameter names this Samba build does not recognise."""
    found = []
    for pattern in (UNKNOWN_PARAM_RE, IGNORING_PARAM_RE):
        for name in pattern.findall(testparm_output or ""):
            lowered = name.strip().lower()
            if lowered not in found:
                found.append(lowered)
    return found


def strip_parameters(config_text: str, names: List[str]) -> str:
    """Drop `key = value` lines whose key is in `names` (Samba keys ignore spaces/case)."""
    if not names:
        return config_text
    wanted = {name.replace(" ", "").lower() for name in names}
    kept = []
    for line in config_text.splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith(("#", ";", "[")) and "=" in stripped:
            key = stripped.split("=", 1)[0].replace(" ", "").lower()
            if key in wanted:
                kept.append(f"#   (unsupported by this Samba build) {stripped}")
                continue
        kept.append(line)
    return "\n".join(kept) + "\n"


# ---------------------------------------------------------------------------
# smb.conf include management
# ---------------------------------------------------------------------------


def include_block(target: str) -> str:
    return f"{BEGIN_MARKER}\n[global]\n   include = {target}\n{END_MARKER}\n"


def has_include(conf_text: str) -> bool:
    return BEGIN_MARKER in conf_text


def add_include(conf_text: str, target: str) -> str:
    if has_include(conf_text):
        return replace_include(conf_text, target)
    separator = "" if conf_text.endswith("\n") or not conf_text else "\n"
    return f"{conf_text}{separator}\n{include_block(target)}"


def replace_include(conf_text: str, target: str) -> str:
    pattern = re.compile(
        re.escape(BEGIN_MARKER) + r".*?" + re.escape(END_MARKER) + r"\n?",
        re.DOTALL,
    )
    return pattern.sub(include_block(target), conf_text)


def remove_include(conf_text: str) -> str:
    pattern = re.compile(
        r"\n*" + re.escape(BEGIN_MARKER) + r".*?" + re.escape(END_MARKER) + r"\n?",
        re.DOTALL,
    )
    return pattern.sub("\n", conf_text)



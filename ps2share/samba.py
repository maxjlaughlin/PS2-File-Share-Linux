NO_SYSTEMD_MARKERS = ("booted with systemd", "Failed to connect to bus", "not found")


def _systemctl(*args: str) -> Result:
    return run(["systemctl", *args], timeout=30)


def systemd_available() -> bool:
    """False inside containers and chroots, where systemctl cannot do anything."""
    if not which("systemctl"):
        return False
    probe = _systemctl("is-system-running")
    return not any(marker in (probe.err or "") for marker in NO_SYSTEMD_MARKERS[:2])


def detect_unit(candidates: Tuple[str, ...]) -> Optional[str]:
    for name in candidates:
        probe = _systemctl("list-unit-files", f"{name}.service", "--no-legend")
        if probe.ok and name in probe.out:
            return name
    # Fall back to asking about the unit directly (works for sysv-generated units).
    for name in candidates:
        probe = _systemctl("show", f"{name}.service", "-p", "LoadState", "--value")
        if probe.ok and probe.text == "loaded":
            return name
    return None


def service_state(unit: Optional[str]) -> Dict[str, object]:
    if not unit:
        # No unit, but smbd may still be running — a container, or started by hand.
        running = any(port in read_listening_ports() for port in (445, 139))
        return {
            "unit": None,
            "active": running,
            "enabled": False,
            "state": "running (not under systemd)" if running else "missing",
        }
    active = _systemctl("is-active", unit)
    enabled = _systemctl("is-enabled", unit)
    state = active.text or "unknown"
    if any(marker in state for marker in NO_SYSTEMD_MARKERS[:2]):
        running = any(port in read_listening_ports() for port in (445, 139))
        return {
            "unit": unit,
            "active": running,
            "enabled": False,
            "state": "running (no systemd here)" if running else "stopped (no systemd here)",
        }
    return {
        "unit": unit,
        "active": state == "active",
        "enabled": enabled.text in ("enabled", "enabled-runtime", "static"),
        "state": state,
    }


def samba_status() -> Dict[str, object]:
    smbd = detect_unit(SMBD_UNITS)
    nmbd = detect_unit(NMBD_UNITS)
    return {
        "installed": samba_installed(),
        "version": samba_version(),
        "smbd": service_state(smbd),
        "nmbd": service_state(nmbd),
    }


def reload_samba() -> Result:
    """Nudge smbd into re-reading its config, preferring the non-disruptive route."""
    if which("smbcontrol"):
        result = run(["smbcontrol", "all", "reload-config"], timeout=30)
        if result.ok:
            return result
    unit = detect_unit(SMBD_UNITS)
    if not unit:
        return Result(1, "", "could not find the smbd service unit")
    result = _systemctl("reload", unit)
    if result.ok:
        return result
    return _systemctl("restart", unit)


def control_service(action: str) -> Result:
    if action not in ("start", "stop", "restart", "reload", "enable", "disable"):
        return Result(2, "", f"unsupported action: {action}")
    if action == "reload":
        return reload_samba()
    unit = detect_unit(SMBD_UNITS)
    if not unit:
        return Result(1, "", "could not find the smbd service unit")
    result = _systemctl(action, unit)
    nmb = detect_unit(NMBD_UNITS)
    if nmb and action in ("start", "restart", "enable"):
        _systemctl(action, nmb)
    elif nmb and action in ("stop", "disable"):
        _systemctl(action, nmb)
    return result



def create_system_user(name: str, home: str = "") -> Result:
    """Create a locked, no-login system account to own the share."""
    if user_exists(name):
        return Result(0, f"user {name} already exists", "")
    cmd = ["useradd", "--system", "--shell", "/usr/sbin/nologin"]
    if home:
        cmd += ["--home-dir", home, "--no-create-home"]
    else:
        cmd += ["--no-create-home"]
    cmd.append(name)
    return run(cmd, timeout=30)


def set_smb_password(username: str, password: str) -> Result:
    """Add or update the Samba password for an existing unix account."""
    if not which("smbpasswd"):
        return Result(127, "", "smbpasswd not found — is Samba installed?")
    if not user_exists(username):
        return Result(2, "", f"unix account '{username}' does not exist")
    if not password:
        return Result(2, "", "password must not be empty")
    added = run(["smbpasswd", "-a", "-s", username], timeout=30, stdin=f"{password}\n{password}\n")
    if not added.ok:
        return added
    return run(["smbpasswd", "-e", username], timeout=30)


def smb_user_exists(username: str) -> bool:
    if not which("pdbedit"):
        return False
    probe = run(["pdbedit", "-L", "-u", username], timeout=15)
    return probe.ok and username in probe.out



"""Generating, validating and applying the Samba configuration OPL needs.

Open PS2 Loader speaks SMB1 (the NT LM 0.12 dialect) and authenticates with
NTLMv1.  Every modern Samba ships with both switched off, which is why a
stock `smb.conf` is invisible to a PlayStation 2.  Everything in this module
exists to put those switches back — for one share — without disturbing
whatever else the server is already sharing.

The strategy is a drop-in file (`ps2share.conf`) pulled into `smb.conf` by a
single marked `include` line.  The user's own config is backed up, never
rewritten, and `uninstall` can lift the block straight back out.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple

from .config import Config
from .monitor import read_listening_ports
from .util import (
    Result,
    atomic_write,
    backup_file,
    group_of_user,
    is_root,
    owner_of_path,
    run,
    user_exists,
    which,
)

BEGIN_MARKER = "#### BEGIN ps2share — managed by PS2 File Share, do not edit ####"
END_MARKER = "#### END ps2share ####"

DEFAULT_SMB_CONF = "/etc/samba/smb.conf"

# Unit names differ between distributions: Debian/Ubuntu use smbd/nmbd,
# RHEL/Fedora/Arch use smb/nmb.
SMBD_UNITS = ("smbd", "smb")
NMBD_UNITS = ("nmbd", "nmb")


@dataclass
class ApplyOutcome:
    ok: bool
    message: str
    details: str = ""
    config_text: str = ""
    # True once the config is on disk and testparm accepted it, even if the
    # service could not then be started — the settings are worth remembering.
    written: bool = False


def smb_conf_path() -> str:
    """Ask smbd where its config lives, falling back to the usual location."""
    binary = which("smbd")
    if binary:
        probe = run([binary, "-b"], timeout=10)
        if probe.ok:
            match = re.search(r"^\s*CONFIGFILE:\s*(\S+)\s*$", probe.out, re.MULTILINE)
            if match:
                return match.group(1)
    return DEFAULT_SMB_CONF


def include_path(conf: Optional[str] = None) -> str:
    base = os.path.dirname(conf or smb_conf_path()) or "/etc/samba"
    return os.path.join(base, "ps2share.conf")


def samba_version() -> str:
    for binary in ("smbd", "smbstatus", "samba"):
        path = which(binary)
        if not path:
            continue
        probe = run([path, "--version"], timeout=10)
        if probe.ok:
            return probe.text.replace("Version", "").strip()
    return ""


def version_tuple(version: str) -> Tuple[int, ...]:
    match = re.match(r"(\d+)\.(\d+)\.(\d+)", version or "")
    if not match:
        return ()
    return tuple(int(part) for part in match.groups())


def samba_installed() -> bool:
    return which("smbd") is not None or which("smbstatus") is not None


